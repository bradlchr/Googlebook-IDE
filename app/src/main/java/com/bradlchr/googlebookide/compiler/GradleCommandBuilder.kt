package com.bradlchr.googlebookide.compiler

import java.io.File
import java.security.MessageDigest

object GradleCommandBuilder {

    /**
     * Builds the ./gradlew execution command according to Android Laptop Developer
     * and App Developer specifications, guaranteeing --project-cache-dir redirection
     * to native ext4 storage.
     */
    fun build(
        projectPath: String,
        task: String = "assembleDebug",
        clean: Boolean = false,
        extraArgs: List<String> = emptyList()
    ): List<String> {
        val file = File(projectPath)
        val baseName = file.name
        val canonical = try { file.canonicalPath } catch (e: Exception) { file.absolutePath }
        val sha1 = computeSha1Prefix(canonical, 8)
        val home = System.getenv("HOME") ?: "/home/droid"
        val cacheDir = "$home/.cache/projects/$baseName-$sha1/gradle"

        val cmd = mutableListOf("./gradlew")
        if (clean) {
            cmd.add("clean")
        }
        cmd.add(task)
        cmd.add("--project-cache-dir=$cacheDir")
        cmd.addAll(extraArgs)
        return cmd
    }

    /**
     * Returns the standard output APK path generated by Gradle application variants.
     */
    fun getStandardApkPath(projectPath: String, appName: String, isDebug: Boolean = true): String {
        val variant = if (isDebug) "debug" else "release"
        return "$projectPath/app/build/outputs/apk/$variant/$appName-$variant.apk"
    }

    private fun computeSha1Prefix(text: String, length: Int): String {
        return try {
            val md = MessageDigest.getInstance("SHA-1")
            val bytes = md.digest(text.toByteArray(Charsets.UTF_8))
            bytes.joinToString("") { "%02x".format(it) }.take(length)
        } catch (e: Exception) {
            "default"
        }
    }
}
